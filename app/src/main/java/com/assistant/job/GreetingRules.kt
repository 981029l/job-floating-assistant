    private val matchingRules = """
【逐项匹配规则】
1. 逐项核对 JD 的工作职责、任职要求和补充招聘要求，分别识别主要交付工作、明确技术要求、明确优先项及企业背景。保留原文限定词；同一能力同时出现在“优先”和普通要求中时标为待确认，不能自行降为无关加分项。并列框架列表未说明全部必需或任选时，不擅自作出任一结论。
